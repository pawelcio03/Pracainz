  static List<List<String>> readRows({
    required Uint8List bytes,
    String fileName = 'import.csv',
  }) {
    if (isSpreadsheet(fileName)) {
      return _readXlsxRows(bytes);
    }

    final decoded = _decodeDelimitedText(bytes);
    return CsvUtils.parseRows(decoded);
  }

  static bool isSpreadsheet(String fileName) {
    final normalized = fileName.trim().toLowerCase();
    return normalized.endsWith('.xlsx');
  }

  static List<List<String>> _readXlsxRows(Uint8List bytes) {
    final excel = Excel.decodeBytes(bytes);
    for (final table in excel.tables.values) {
      final rows = table.rows
          .map(
            (row) => row
                .map(
                  (cell) => cell == null
                      ? ''
                      : _cellValueToString(
                          cell.value,
                          cell.cellStyle?.numberFormat,
                        ),
                )
                .toList(),
          )
          .toList();

      final hasData = rows.any(
        (row) => row.any((cell) => cell.trim().isNotEmpty),
      );
      if (hasData) {
        return rows;
      }
    }

    return const <List<String>>[];
  }

  static String _decodeDelimitedText(Uint8List bytes) {
    final content = _withoutUtf8Bom(bytes);

    try {
      return utf8.decode(content);
    } on FormatException {
      final candidates =
          [
            _decodeSingleByte(content, _windows1250CodePoints),
            _decodeSingleByte(content, _iso88592CodePoints),
            latin1.decode(content),
          ]..sort((left, right) {
            return _textQualityScore(right).compareTo(_textQualityScore(left));
          });

      return candidates.first;
    }
  }

  static Uint8List _withoutUtf8Bom(Uint8List bytes) {
    if (bytes.length >= 3 &&
        bytes[0] == 0xEF &&
        bytes[1] == 0xBB &&
        bytes[2] == 0xBF) {
      return Uint8List.sublistView(bytes, 3);
    }

    return bytes;
  }

  static String _decodeSingleByte(Uint8List bytes, Map<int, int> codePoints) {
    final buffer = StringBuffer();
    for (final byte in bytes) {
      if (byte < 0x80) {
        buffer.writeCharCode(byte);
        continue;
      }

      buffer.writeCharCode(codePoints[byte] ?? byte);
    }

    return buffer.toString();
  }

  static int _textQualityScore(String text) {
    var score = 0;
    for (final rune in text.runes) {
      if (rune == 0xFFFD) {
        score -= 100;
      } else if (rune < 0x20 && rune != 0x09 && rune != 0x0A && rune != 0x0D) {
        score -= 30;
      } else if (_polishCodePoints.contains(rune)) {
        score += 5;
      }
    }

    return score;
  }

  static String _cellValueToString(CellValue? value, NumFormat? format) {
    switch (value) {
      case null:
        return '';
      case TextCellValue():
        return value.value.text ?? '';
      case FormulaCellValue():
        return value.formula;
      case IntCellValue():
        return value.value.toString();
      case DoubleCellValue():
        return value.value.toString();
      case BoolCellValue():
        return value.value ? 'true' : 'false';
      case DateCellValue():
        return value.asDateTimeLocal().toIso8601String();
      case DateTimeCellValue():
        return value.asDateTimeLocal().toIso8601String();
      case TimeCellValue():
        return value.asDuration().toString();
    }
  }

